import assert from 'node:assert/strict';
import { CHECKS, assessFreshness, checkMonitorFreshness } from '../scripts/check-monitor-freshness.mjs';
const now = Date.parse('2026-10-21T17:00:00Z');
const workflow = { state: 'active' };
const good = { id: 1, event: 'schedule', status: 'completed', conclusion: 'success', head_branch: 'main', updated_at: '2026-10-21T14:30:00Z' };
assert.equal(assessFreshness(CHECKS[0], workflow, [good], now).state, 'current');
assert.equal(assessFreshness(CHECKS[0], workflow, [{ ...good, event: 'push' }], now).state, 'unverified', 'A new push cannot conceal a missing scheduled run.');
assert.equal(assessFreshness(CHECKS[0], workflow, [{ ...good, updated_at: '2026-10-19T14:30:00Z' }, { ...good, id: 2, event: 'push' }], now).state, 'stale');
assert.equal(assessFreshness(CHECKS[0], workflow, [{ ...good, conclusion: 'failure' }], now).state, 'unverified');
assert.equal(assessFreshness(CHECKS[0], workflow, [{ ...good, head_branch: 'feature' }], now).state, 'unverified');
assert.equal(assessFreshness(CHECKS[0], workflow, [{ ...good, updated_at: '2026-10-19T14:30:00Z' }], now).state, 'stale');
assert.equal(assessFreshness(CHECKS[1], workflow, [{ ...good, updated_at: '2026-10-19T14:30:00Z' }], now).state, 'current', 'Weekly Mac checks are not overdue after two days.');
assert.equal(assessFreshness(CHECKS[1], workflow, [{ ...good, updated_at: '2026-10-12T14:30:00Z' }], now).state, 'stale');
assert.equal(assessFreshness(CHECKS[0], { state: 'disabled_inactivity' }, [good], now).state, 'disabled');
assert.equal(assessFreshness(CHECKS[0], workflow, [{ ...good, updated_at: '2027-01-01T00:00:00Z' }], now).state, 'invalid_time');
const calls = [];
const rows = checkMonitorFreshness('synthetic/repo', endpoint => { calls.push(endpoint); return endpoint.includes('/runs?') ? { workflow_runs: [good] } : workflow; }, now);
assert.ok(rows.every(row => row.state === 'current'));
assert.equal(calls.length, 6);
assert.ok(calls.every(path => path.startsWith('repos/synthetic/repo/actions/workflows/')));
assert.ok(calls.filter(path => path.includes('/runs?')).every(path => path.includes('event=schedule')));
assert.throws(() => checkMonitorFreshness('https://another.host/', () => { throw Error('must not call'); }), /valid repository/);
console.log('PASS: stale/disabled/unverified monitoring coverage, weekly Mac cadence and read-only workflow checks.');
