import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { readFile } from 'node:fs/promises';
import express from 'express';
import { connect, initSchema, dbRun, dbGet, close } from '../db.js';
import { initSignaturePolicySchema, pinApprovedOwnerSignature } from '../signature-policy.js';
import { mountReportSignature } from '../report-signature.js';

assert.equal(process.env.DATABASE_URL || '', '', 'Only isolated synthetic storage is allowed.');
assert.equal(process.env.PGLITE_DIR || '', '', 'Existing records must not be used.');
await connect(); await initSchema(); await initSignaturePolicySchema();
const png = Buffer.from((await readFile(new URL('./signature.b64', import.meta.url), 'utf8')).trim(), 'base64');
const sha = value => crypto.createHash('sha256').update(value).digest('hex');
const secret = 'synthetic-signature-contract-only';
const now = 1800000000;
let listener;
const stamp = new Date().toISOString();
const claims = { aud: 'stone-square-report-generator', email: 'owner@example.test', name: 'Synthetic Owner', role: 'owner', permissions: ['reports.create'], issuedAt: now, expiresAt: now + 300 };
const assertion = (changes = {}) => { const body = Buffer.from(JSON.stringify({ ...claims, ...changes })).toString('base64url'); return body + '.' + crypto.createHmac('sha256', secret).update(body).digest('base64url'); };
try {
  const result = await dbRun('INSERT INTO users(email,password_hash,name,role,created_at) VALUES (?,?,?,?,?)', [claims.email, 'unused', claims.name, 'owner', stamp]);
  const userId = result.lastID;
  await dbRun('INSERT INTO profile_signatures(user_id,signature_bytes,signature_type,updated_at) VALUES (?,?,?,?)', [userId, png, 'drawn', stamp]);
  const app = express();
  mountReportSignature(app, { secret, rateLimit: () => (_req, _res, next) => next(), now: () => now });
  app.use((error, _req, res, _next) => res.status(error.statusCode || 500).json({ error: error.message }));
  listener = await new Promise(resolve => { const server = app.listen(0, '127.0.0.1', () => resolve(server)); });
  const url = `http://127.0.0.1:${listener.address().port}/api/reports/signature`;
  const call = token => fetch(url, { method: 'POST', headers: token ? { Authorization: `Bearer ${token}` } : {} });
  assert.equal((await call()).status, 401);
  assert.equal((await call('invalid')).status, 401);
  assert.equal((await call(assertion({ aud: 'another-service' }))).status, 401);
  assert.equal((await call(assertion({ expiresAt: now }))).status, 401);
  assert.equal((await call(assertion({ expiresAt: now + 301 }))).status, 401);
  assert.equal((await call(assertion({ role: 'secretary' }))).status, 403);
  assert.equal((await call(assertion())).status, 409, 'An unapproved profile must never be used.');
  await pinApprovedOwnerSignature({ ownerUserId: userId, expectedProfileSha256: sha(png), authorizationNote: 'Synthetic approval in an isolated test only.' });
  const beforeProfile = await dbGet('SELECT * FROM profile_signatures WHERE user_id=?', [userId]);
  const beforePolicy = await dbGet('SELECT * FROM owner_signature_policies WHERE user_id=?', [userId]);
  const beforeAudit = await dbGet('SELECT COUNT(*) AS count FROM audit_events');
  const response = await call(assertion());
  assert.equal(response.status, 200);
  assert.match(response.headers.get('content-type'), /^image\/png/);
  assert.equal(response.headers.get('cache-control'), 'private, no-store');
  assert.equal(response.headers.get('x-signature-sha256'), sha(png));
  assert.deepEqual(Buffer.from(await response.arrayBuffer()), png);
  assert.deepEqual(await dbGet('SELECT * FROM profile_signatures WHERE user_id=?', [userId]), beforeProfile);
  assert.deepEqual(await dbGet('SELECT * FROM owner_signature_policies WHERE user_id=?', [userId]), beforePolicy);
  assert.deepEqual(await dbGet('SELECT COUNT(*) AS count FROM audit_events'), beforeAudit, 'A profile read must not create signature or report events.');
  await dbRun('UPDATE profile_signatures SET signature_bytes=? WHERE user_id=?', [Buffer.concat([png, Buffer.from('changed')]), userId]);
  assert.equal((await call(assertion())).status, 409, 'A different image cannot bypass the pinned signature.');
  await dbRun('UPDATE users SET access_revoked_at=? WHERE id=?', [stamp, userId]);
  assert.equal((await call(assertion())).status, 403, 'A signed assertion does not override current revoked access.');
  await dbRun('UPDATE users SET access_revoked_at=NULL,name=? WHERE id=?', ['Changed Name', userId]);
  assert.equal((await call(assertion())).status, 403);
  console.log('PASS: owner report signature assertion, current access, pinned image, integrity, no cache and read-only behavior.');
} finally { if (listener) await new Promise(resolve => listener.close(resolve)); await close(); }
